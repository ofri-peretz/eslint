#!/usr/bin/env -S npx tsx
/**
 * Gate: are this week's benchmark artifacts actually publishable?
 *
 * Exists because of a real incident. On 2026-05-11 a partial flagship
 * snapshot (1 rule of 10) landed in results/. The scorecard loader requires
 * all 10, so it silently fell back to the 05-10 snapshot — and the published
 * numbers sat three months stale while the bench looked like it had run.
 * Every command in that pipeline exited 0.
 *
 * So this asserts the properties the numbers must have, not that a process
 * exited cleanly:
 *
 *   1. FRESH      — the snapshot the scorecard READS was generated by THIS
 *                   run, not recovered from an older file.
 *   2. COMPLETE   — the flagship snapshot covers every manifest rule.
 *   3. COMPARABLE — the headline's ESLint stacks linted the same file set.
 *                   Otherwise the bars measure different work.
 *   4. HONEST     — no stack is recorded as failed-but-timed. A crash must
 *                   never be published as a fast run.
 *
 * Exit 1 = do not publish.
 */
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');
const HEADLINE_DIR = resolve(REPO_ROOT, 'benchmarks/results/ilb-headline');
const FLAGSHIP_DIR = resolve(REPO_ROOT, 'benchmarks/results/ilb-flagship');
const MANIFEST = resolve(REPO_ROOT, 'benchmarks/suites/ilb-flagship/manifest.json');

const failures: string[] = [];
const warnings: string[] = [];
const notes: string[] = [];

/** Anything older than this is not "this run". */
const MAX_AGE_MIN = Number(process.env.BENCH_MAX_AGE_MIN || 180);

function ageMinutes(iso: string): number {
  return (Date.now() - new Date(iso).getTime()) / 60000;
}

function latest(dir: string): string | null {
  if (!existsSync(dir)) return null;
  const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  return files.length ? files[files.length - 1] : null;
}

// ── 1. Headline ────────────────────────────────────────────────────────
const headlineFile = latest(HEADLINE_DIR);
if (!headlineFile) {
  failures.push('No headline snapshot produced — ilb:headline did not write a result.');
} else {
  const h = JSON.parse(readFileSync(join(HEADLINE_DIR, headlineFile), 'utf8'));

  // FRESH
  const age = h.generatedAt ? ageMinutes(h.generatedAt) : Infinity;
  if (!Number.isFinite(age)) {
    failures.push('Headline snapshot has no generatedAt — cannot prove freshness.');
  } else if (age > MAX_AGE_MIN) {
    failures.push(
      `Headline snapshot is ${Math.round(age)} min old (limit ${MAX_AGE_MIN}). ` +
      `It was NOT produced by this run — publishing it would republish stale numbers.`,
    );
  } else {
    notes.push(`Headline snapshot fresh (${Math.round(age)} min old).`);
  }

  // COMPARABLE
  if (!h.fileSet?.eslintParity) {
    failures.push(
      `Headline ESLint stacks linted different file sets ` +
      `(ours=${h.fileSet?.ours}, competitor=${h.fileSet?.competitor}). ` +
      `The bars would compare different work.`,
    );
  } else {
    notes.push(`File-set parity verified (${h.fileSet.ours} files per ESLint stack).`);
  }
  if (h.fileSet?.oxlintParity === null || h.fileSet?.oxlintParity === false) {
    warnings.push(
      'oxlint file-set parity unverified — its bar is indicative, not a like-for-like ' +
      'comparison. The rendered caveat must say so.',
    );
  }

  // HONEST
  for (const [key, stack] of Object.entries<any>(h.stacks ?? {})) {
    for (const phase of ['cold', 'warm'] as const) {
      const run = stack?.[phase];
      if (!run) { failures.push(`Headline stack ${key}.${phase} missing entirely.`); continue; }
      if (!run.ok) {
        warnings.push(`Headline stack ${key}.${phase} FAILED: ${run.note ?? 'no detail'} (excluded from chart).`);
        continue;
      }
      if (typeof run.median !== 'number' || !(run.median > 0)) {
        failures.push(`Headline stack ${key}.${phase} has a non-positive median (${run.median}).`);
      }
      // A "successful" run that processed nothing is the classic silent-zero:
      // a bad glob makes a stack look infinitely fast.
      if (phase === 'cold' && key !== 'oxlintNative' && !(run.filesProcessed > 0)) {
        failures.push(
          `Headline stack ${key}.cold processed 0 files but reported success — ` +
          `a bad glob would render this as an impossibly fast bar.`,
        );
      }
    }
  }

  // At least two stacks must be publishable or there is no comparison.
  const okStacks = Object.values<any>(h.stacks ?? {}).filter((s) => s?.cold?.ok).length;
  if (okStacks < 2) {
    failures.push(`Only ${okStacks} stack(s) produced a usable cold number — nothing to compare.`);
  }
}

// ── 2. Flagship ────────────────────────────────────────────────────────
// Advisory, not blocking: the headline chart is the published number and can
// ship without the per-rule scorecard. But a partial snapshot must be called
// out loudly, because that is exactly the failure that caused the 3-month drift.
const flagshipFile = latest(FLAGSHIP_DIR);
if (!flagshipFile) {
  warnings.push('No flagship snapshot found — per-rule scorecard not refreshed this run.');
} else {
  const f = JSON.parse(readFileSync(join(FLAGSHIP_DIR, flagshipFile), 'utf8'));
  const expected = JSON.parse(readFileSync(MANIFEST, 'utf8')).rules?.length ?? 0;
  const got = f.results?.length ?? 0;

  if (got < expected) {
    warnings.push(
      `Flagship snapshot ${flagshipFile} covers ${got}/${expected} rules. ` +
      `The scorecard loader requires all ${expected}, so it will SILENTLY FALL BACK ` +
      `to an older complete snapshot — the published per-rule numbers will not be ` +
      `from this run. Re-run ilb:flagship before trusting the scorecard's date.`,
    );
  } else {
    notes.push(`Flagship snapshot complete (${got}/${expected} rules).`);
    const fAge = f.generatedAt ? ageMinutes(f.generatedAt) : null;
    if (fAge !== null && fAge > MAX_AGE_MIN) {
      warnings.push(`Flagship snapshot is ${Math.round(fAge)} min old — likely not from this run.`);
    }
  }
}

// ── Report ─────────────────────────────────────────────────────────────
console.log('\n=== Weekly benchmark verification ===\n');
for (const n of notes) console.log(`  ok      ${n}`);
for (const w of warnings) console.log(`  WARN    ${w}`);
for (const e of failures) console.log(`  FAIL    ${e}`);
console.log('');

if (failures.length > 0) {
  console.error(`${failures.length} blocking problem(s) — NOT publishable.`);
  process.exit(1);
}
console.log(`Publishable.${warnings.length ? ` (${warnings.length} warning(s) — read them.)` : ''}`);
