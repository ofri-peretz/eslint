#!/usr/bin/env node
/**
 * Which of our rules does oxlint already ship natively?
 *
 * Joins every `eslint-plugin-*` rule name against `oxlint --rules --format json` (the
 * oxlint this repo installs) and writes:
 *   - docs/oxlint-builtin-overlap.json — data the docs app and the alias READMEs render
 *   - docs/oxlint-builtin-overlap.md   — the same, for humans
 *
 * A name match is not a behaviour match (react-features `no-typos` vs `nextjs/no-typos`),
 * so every overlap needs a human verdict in scripts/oxlint-builtin-overlap.triage.json:
 *   equivalent     — oxlint's native rule does the same job; oxlint users can use it
 *   differs        — similar native rule, different behaviour (say how in `note`)
 *   false-positive — names collide, rules are unrelated
 *
 * `--check` exits 1 when an overlap has no verdict (an oxlint upgrade added a native
 * rule — triage it), when a verdict names an overlap that no longer exists, or when the
 * committed outputs are stale. `generatedAt` is ignored by the comparison.
 *
 * Usage: npx tsx scripts/oxlint-builtin-overlap.ts [--check]
 */
import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';
import { extractRuleNamesFromIndex } from './sync-readme-rules';

const ROOT = path.join(__dirname, '..');
const PACKAGES = path.join(ROOT, 'packages');
const TRIAGE = path.join(__dirname, 'oxlint-builtin-overlap.triage.json');
const OUT_JSON = path.join(ROOT, 'docs', 'oxlint-builtin-overlap.json');
const OUT_MD = path.join(ROOT, 'docs', 'oxlint-builtin-overlap.md');
const OXLINT = path.join(ROOT, 'node_modules', '.bin', 'oxlint');

export type Verdict = 'equivalent' | 'differs' | 'false-positive';
export interface Triage {
  [id: string]: { builtin: string; verdict: Verdict; note?: string };
}
export interface OverlapEntry {
  id: string;
  plugin: string;
  rule: string;
  builtin: string;
  verdict: Verdict;
  note?: string;
}

/** Name joins: `<plugin>/<rule>` → every native `<scope>/<rule>` with the same rule name. */
export function findOverlaps(
  ours: Record<string, string[]>,
  builtins: { scope: string; value: string }[],
): Map<string, string[]> {
  const byName = new Map<string, string[]>();
  for (const b of builtins)
    byName.set(b.value, [
      ...(byName.get(b.value) ?? []),
      `${b.scope}/${b.value}`,
    ]);
  const out = new Map<string, string[]>();
  for (const [plugin, rules] of Object.entries(ours))
    for (const rule of rules) {
      const hits = byName.get(rule);
      if (hits) out.set(`${plugin}/${rule}`, hits.toSorted());
    }
  return out;
}

/** Problems that make `--check` fail. */
export function triageProblems(
  overlaps: Map<string, string[]>,
  triage: Triage,
): string[] {
  const problems: string[] = [];
  for (const [id, hits] of overlaps) {
    const t = triage[id];
    if (!t) problems.push(`untriaged: ${id} ↔ ${hits.join(' | ')}`);
    else if (!hits.includes(t.builtin))
      problems.push(
        `${id}: triaged builtin ${t.builtin} is not among ${hits.join(' | ')}`,
      );
  }
  for (const id of Object.keys(triage))
    if (!overlaps.has(id)) problems.push(`stale triage entry: ${id}`);
  return problems;
}

function ourRules(): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const dir of fs
    .readdirSync(PACKAGES)
    .filter((d) => d.startsWith('eslint-plugin-'))
    .sort())
    out[dir.slice('eslint-plugin-'.length)] = extractRuleNamesFromIndex(
      path.join(PACKAGES, dir),
    );
  return out;
}

function renderMd(doc: {
  oxlintVersion: string;
  builtinRuleCount: number;
  overlap: OverlapEntry[];
}): string {
  const lines = [
    '# Our rules that oxlint ships natively',
    '',
    '> Generated by `scripts/oxlint-builtin-overlap.ts` — do not edit. Verdicts live in',
    '> `scripts/oxlint-builtin-overlap.triage.json`.',
    '',
    `oxlint ${doc.oxlintVersion} ships ${doc.builtinRuleCount} built-in rules. On oxlint, prefer the native`,
    'rule where the verdict is **equivalent**: it runs in Rust and avoids double-reporting.',
    '',
    '| Our rule | Native rule | Verdict | Note |',
    '| :------- | :---------- | :------ | :--- |',
    ...doc.overlap.map(
      (e) =>
        `| \`${e.id}\` | \`${e.builtin}\` | ${e.verdict} | ${e.note ?? ''} |`,
    ),
    '',
  ];
  return lines.join('\n');
}

function main(): void {
  const check = process.argv.includes('--check');
  const builtins = JSON.parse(
    execFileSync(OXLINT, ['--rules', '--format', 'json'], {
      encoding: 'utf-8',
    }),
  ) as { scope: string; value: string }[];
  const oxlintVersion = execFileSync(OXLINT, ['--version'], {
    encoding: 'utf-8',
  })
    .replace(/^Version:\s*/, '')
    .trim();
  const triage = JSON.parse(fs.readFileSync(TRIAGE, 'utf-8')) as Triage;
  const overlaps = findOverlaps(ourRules(), builtins);

  const problems = triageProblems(overlaps, triage);
  if (problems.length) {
    console.error(problems.map((p) => `✗ ${p}`).join('\n'));
    console.error(`\nAdd or fix verdicts in ${path.relative(ROOT, TRIAGE)}.`);
    process.exit(1);
  }

  const overlap: OverlapEntry[] = [...overlaps.keys()].toSorted().map((id) => {
    const [plugin, rule] = id.split('/');
    return { id, plugin, rule, ...triage[id] };
  });
  const doc = {
    generatedAt: new Date().toISOString(),
    oxlintVersion,
    builtinRuleCount: builtins.length,
    overlap,
  };
  const md = renderMd(doc);

  if (check) {
    const strip = (s: string) => s.replace(/"generatedAt": "[^"]*"/, '');
    const stale = [
      [OUT_JSON, `${JSON.stringify(doc, null, 2)}\n`],
      [OUT_MD, md],
    ].filter(
      ([f, want]) =>
        !fs.existsSync(f) || strip(fs.readFileSync(f, 'utf-8')) !== strip(want),
    );
    if (stale.length) {
      console.error(
        stale.map(([f]) => `✗ stale: ${path.relative(ROOT, f)}`).join('\n'),
      );
      console.error('\nRun `npm run oxlint:overlap` and commit the result.');
      process.exit(1);
    }
    console.log(`✓ ${overlap.length} overlaps, all triaged, outputs current`);
    return;
  }
  fs.writeFileSync(OUT_JSON, `${JSON.stringify(doc, null, 2)}\n`);
  fs.writeFileSync(OUT_MD, md);
  console.log(
    `✓ wrote ${overlap.length} overlaps (oxlint ${oxlintVersion}, ${builtins.length} built-ins)`,
  );
}

if (require.main === module) main();
