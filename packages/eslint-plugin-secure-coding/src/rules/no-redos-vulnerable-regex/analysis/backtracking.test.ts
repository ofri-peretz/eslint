describe('analyse', () => {
  it.each(TABLE)('%s /%s', (source, flags, expected) => {
    expect(reports(source, flags)).toBe(expected);
  });

  it('a v-flag class holding strings is declined, not guessed', () => {
    expect(() => reports('(?:[\\q{ab}]+)+', 'v')).toThrow(
      UnsupportedPatternError,
    );
  });

  it('a backreference that may mean several groups is declined', () => {
    expect(() => reports('(?:(?<n>a+)|(?<n>b+))\\k<n>+', '')).toThrow(
      UnsupportedPatternError,
    );
  });

  it('a pattern with nothing unbounded has nothing to report', () => {
    expect(reports('^[a-z]{1,8}$', '')).toBe('');
    expect(reports('', '')).toBe('');
  });
});
