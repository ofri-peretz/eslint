const flagsOf = (f: string): Flags => ({
  ignoreCase: f.includes('i'),
  unicode: f.includes('u'),
  unicodeSets: f.includes('v'),
  dotAll: f.includes('s'),
  multiline: f.includes('m'),
});

/** `S` / `T` per report (Self, Trade), `!` when exponential. */
function reports(source: string, flags: string): string {
  const pattern = new RegExpParser().parsePattern(source, 0, source.length, {
    unicode: flags.includes('u'),
    unicodeSets: flags.includes('v'),
  });
  return analyse({ pattern, flags: flagsOf(flags) })
    .reports.map((r) => r.type[0] + (r.exponential ? '!' : ''))
    .join('');
}

