/**
 * The report names the parameter that matched.
 *
 * tolaria's mobile app ships a 1.1 MB generated HTML bundle as one string
 * literal, React inlined. The rule reported at the literal's first character
 * and said only "Credentials detected in URL query parameters", which left a
 * reader to search a megabyte for the cause. The cause is minified router
 * code — `&&t.password===e.password` reads as `&` + `t.password` + `=` — and
 * the message now says `t.password`, which is enough to find it and to see it
 * is code, not a URL.
 *
 * The match itself stands: a string is the only evidence this rule has, and a
 * query key may contain a dot (`?user.password=`). The plugin has no
 * convention for skipping generated files, and the repo's reporting posture is
 * to let the consumer scope them (`ignores` in their config).
 */
import { RuleTester } from '@typescript-eslint/rule-tester';
import { describe, it, expect, afterAll } from 'vitest';
import parser from '@typescript-eslint/parser';
import { Linter } from 'eslint';
import { noCredentialsInQueryParams } from './index';

RuleTester.afterAll = afterAll;
RuleTester.it = it;
RuleTester.itOnly = it.only;
RuleTester.describe = describe;

const ruleTester = new RuleTester({
  languageOptions: { parser, ecmaVersion: 2022, sourceType: 'module' },
});

describe('no-credentials-in-query-params — the message names the parameter', () => {
  ruleTester.run('names-the-parameter', noCredentialsInQueryParams, {
    valid: [
      {
        name: 'a string with no credential parameter has nothing to name',
        code: `const url = 'https://api.example.com/items?page=2&sort=asc';`,
      },
    ],
    invalid: [
      {
        // @source refactoringhq/tolaria apps/mobile/src/components/workspace/MobileWysiwygTentapEditorHtml.ts:2
        // @found real-source scan
        name: 'a generated bundle: the message says t.password matched, inside minified code',
        code: `// Generated by apps/mobile/scripts/build-wysiwyg-editor-html.mjs.
export const mobileWysiwygTentapEditorHtml = "<script>function Lx(t,e){return t.port===e.port&&t.hash===e.hash&&t.username===e.username&&t.password===e.password}</script>";`,
        errors: [
          { messageId: 'violationDetected', data: { param: 't.password' } },
        ],
      },
      {
        name: 'a URL: the message names the parameter',
        code: 'const url = `https://api.example.com/v1?client_id=${id}&client_secret=${secret}`;',
        errors: [
          { messageId: 'violationDetected', data: { param: 'client_secret' } },
        ],
      },
      {
        name: 'a reset link that also carries an api key names the api key, not the exempt token',
        code: `const url = 'https://app.example.com/reset?token=abc&apikey=xyz';`,
        errors: [{ messageId: 'violationDetected', data: { param: 'apikey' } }],
      },
    ],
  });
});

/**
 * `data` in a RuleTester error is checked by rendering the message with it, so
 * it cannot fail against a template that has no `{{param}}` slot. The rendered
 * text is the thing a reader sees; assert on it.
 */
describe('no-credentials-in-query-params — the rendered message', () => {
  it('contains the matched parameter name', () => {
    const linter = new Linter({ configType: 'flat' });
    const [message] = linter.verify(
      'const html = "<script>return t.username===e.username&&t.password===e.password</script>";',
      {
        plugins: { b: { rules: { r: noCredentialsInQueryParams } } },
        rules: { 'b/r': 'error' },
      } as unknown as Linter.Config,
    );
    expect(message?.message).toContain('`t.password`');
  });
});
