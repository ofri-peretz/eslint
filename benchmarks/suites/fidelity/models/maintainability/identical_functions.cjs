const { tag } = require('../../lib.cjs');
const { keyOf, src } = require('../../quality.cjs');

const PRICE = [
  '{',
  '  const total = order.items.reduce((sum, item) => sum + item.price * item.qty, 0);',
  '  const tax = total * order.rate;',
  '  return { id: order.id, total, tax };',
  '}',
];
// The same tokens, laid out differently and commented.
const PRICE_REFORMATTED = [
  '{',
  '  // sum the lines first',
  '  const total = order.items.reduce(',
  '    (sum, item) => sum + item.price * item.qty,',
  '    0',
  '  );',
  '  const tax = total * order.rate; /* then tax */',
  '  return {',
  '    id: order.id,',
  '    total,',
  '    tax',
  '  };',
  '}',
];
const LABEL = [
  '{',
  '  const name = order.customer.trim().toUpperCase();',
  '  if (!name) throw new Error(`order ${order.id} has no customer`);',
  '  return `${name}#${order.id}`;',
  '}',
];
const SHORT = ['{ return order.items.length + order.id; }'];

const BODIES = {
  Identical: [PRICE, PRICE],
  Reformatted: [PRICE, PRICE_REFORMATTED],
  Different: [PRICE, LABEL],
  ShortIdentical: [SHORT, SHORT],
};

const fn = (kind, name, body) => {
  const [first, ...rest] = body;
  switch (kind) {
    case 'decl':
      return [`export function ${name}(order: Order) ${first}`, ...rest];
    case 'arrow': {
      const lines = [
        `export const ${name} = (order: Order) => ${first}`,
        ...rest,
      ];
      lines[lines.length - 1] += ';';
      return lines;
    }
    default:
      return [`  ${name}(order: Order) ${first}`, ...rest.map((l) => `  ${l}`)];
  }
};

function pairCode(pair, [a, b]) {
  switch (pair) {
    case 'DeclDecl':
      return [
        ...fn('decl', 'priceUserOrder', a),
        ...fn('decl', 'priceGuestOrder', b),
      ];
    case 'ArrowArrow':
      return [
        ...fn('arrow', 'priceUserOrder', a),
        ...fn('arrow', 'priceGuestOrder', b),
      ];
    case 'DeclArrow':
      return [
        ...fn('decl', 'priceUserOrder', a),
        ...fn('arrow', 'priceGuestOrder', b),
      ];
    default:
      return [
        'export class Pricing {',
        ...fn('method', 'priceUserOrder', a),
        ...fn('method', 'priceGuestOrder', b),
        '}',
      ];
  }
}

const OPTS = {
  Defaults: {},
  MinLinesOne: { minLines: 1 },
  ExactOnly: { similarityThreshold: 1 },
};

module.exports = {
  rule: 'identical-functions',
  domain: 4 * 4 * 3 * 3 * 2 * 2,
  traces: 3200,
  key: keyOf(
    'pair',
    'body',
    'opts',
    'file',
    'ignoreTestFiles',
    'ignoreGeneratedFiles',
  ),
  config: (s) => {
    const o = { ...OPTS[tag(s.opts)] };
    if (!s.ignoreTestFiles) o.ignoreTestFiles = false;
    if (!s.ignoreGeneratedFiles) o.ignoreGeneratedFiles = false;
    return Object.keys(o).length ? o : undefined;
  },
  filename: (s) =>
    tag(s.file) === 'TestFile' ? 'src/pricing.test.ts' : 'src/pricing.ts',
  code: (s) =>
    src(
      tag(s.file) === 'Generated'
        ? ['/* @generated by pricing-codegen. Do not edit. */']
        : [],
      'interface Item { price: number; qty: number }',
      'interface Order { id: string; rate: number; customer: string; items: Item[] }',
      pairCode(tag(s.pair), BODIES[tag(s.body)]),
    ),
};
