const { tag } = require('../../lib.cjs');
const { keyOf, src } = require('../../quality.cjs');

const FILE = {
  Memory: 'CLAUDE.md',
  Skill: '.claude/skills/ship/SKILL.md',
  Doc: 'docs/contributing.md',
};

/** What the line asks for: something a tool can check, or plain words. */
const TARGET = {
  Code: 'pass `--no-verify` to git',
  Flag: 'push with --force',
  ConfigPath: 'edit renovate.json by hand',
  Plain: 'skip the review',
};

const FORM = {
  LeadNever: (t) => `Never ${t}.`,
  ListAlways: (t) => `- Always ask before you ${t}.`,
  Important: (t) => `IMPORTANT: do not ${t}.`,
  AfterColon: (t) => `Pushing: never ${t}.`,
  ModalActor: (t) => `Agents must not ${t}.`,
  // Descriptions, not rules.
  MidSentence: (t) => `The release job never needs to ${t}.`,
  LowerStart: (t) => `always a reason to ${t} when the build is red.`,
};

const LINK = {
  NoLink: '',
  LeverLink: ' Enforced by [the guard hook](.claude/hooks/guard-bash.mjs).',
  DocLink: ' See [the guide](docs/guide.md).',
};

module.exports = {
  rule: 'enforced-rule-in-prose',
  markdown: true,
  domain: 7 * 4 * 3 * 3 * 3,
  traces: 5000,
  key: keyOf('form', 'target', 'link', 'place', 'context'),
  filename: (s) => FILE[tag(s.place)],
  code: (s) => {
    const line = FORM[tag(s.form)](TARGET[tag(s.target)]) + LINK[tag(s.link)];
    const head =
      tag(s.place) === 'Skill'
        ? ['---', 'name: ship', 'description: Ship a PR.', '---', '']
        : [];
    const c = tag(s.context);
    const body = c === 'Fenced' ? ['```text', line, '```'] : [line];
    const generated =
      c === 'Generated'
        ? ['<!-- generated by scripts/sync-guidance.ts -->']
        : [];
    return src(...generated, ...head, '# Guide', '', ...body);
  },
};
